#!/usr/bin/env python3
"""Generate Matic Map's backend-schema.ts from the views' Python schema.

Every TypedDict a schema module defines becomes an interface, and each named
type it reaches (a `type` alias, a TypedDict or a StrEnum) is emitted once.
`--check` fails when the checked-in file differs from what this generates.
"""

from __future__ import annotations

import argparse
import sys
import types
import typing
from enum import StrEnum
from pathlib import Path

ROOT = Path(__file__).parents[1]
SCHEMAS = (
    "custom_components.matic_robot.map_schema",
    "custom_components.matic_robot.scene_schema",
    "custom_components.matic_robot.plan_schema",
    "custom_components.matic_robot.workspace_schema",
)
OUTPUT = Path("frontend/map-studio-v4/backend-schema.ts")
HEADER = """\
// Generated by scripts/contract_types.py from the schema modules it names.
// Do not edit; run `python scripts/contract_types.py`.
// The JSON the views and the workspace socket send and accept, before Matic
// Map validates it.
"""
SCALARS: dict[object, str] = {
    str: "string",
    int: "number",
    float: "number",
    bool: "boolean",
    types.NoneType: "null",
}


class Emitter:
    """Collect the TypeScript declarations for the named types in a schema."""

    def __init__(self) -> None:
        self.declarations: dict[str, str] = {}

    def reference(self, value: object) -> str:
        """Return the TypeScript type of an annotation, declaring named types."""
        if value in SCALARS:
            return SCALARS[value]
        if value is object:
            return "unknown"
        if isinstance(value, typing.TypeAliasType):
            self.declare(value.__name__, lambda: self.alias(value, value.__value__))
            return value.__name__
        if isinstance(value, type) and issubclass(value, StrEnum):
            members = tuple(member.value for member in value)
            self.declare(
                value.__name__, lambda: self.alias(value, typing.Literal[members])
            )
            return value.__name__
        if typing.is_typeddict(value):
            self.declare(value.__name__, lambda: self.interface(value))
            return value.__name__
        origin, arguments = typing.get_origin(value), typing.get_args(value)
        if origin is typing.Literal:
            return _literals(arguments)
        if origin in (types.UnionType, typing.Union):
            return " | ".join(map(self.reference, arguments))
        if origin is list:
            item = self.reference(arguments[0])
            return f"readonly ({item})[]" if " " in item else f"readonly {item}[]"
        if origin is dict and arguments[0] is str:
            return f"Readonly<Record<string, {self.reference(arguments[1])}>>"
        if origin is tuple:
            return f"readonly [{', '.join(map(self.reference, arguments))}]"
        raise TypeError(f"no TypeScript form for {value!r}")

    def declare(self, name: str, render: typing.Callable[[], str]) -> None:
        """Declare a named type once, in the order the schema first reaches it."""
        if name not in self.declarations:
            self.declarations[name] = ""
            self.declarations[name] = render()

    def alias(self, named: typing.TypeAliasType | type, value: object) -> str:
        return f"export type {named.__name__} = {self.reference(value)};"

    def interface(self, schema: type) -> str:
        hints = typing.get_type_hints(schema, include_extras=True)
        bases = [base for base in schema.__orig_bases__ if typing.is_typeddict(base)]
        inherited = set().union(*(typing.get_type_hints(base) for base in bases))
        heading = f"export interface {schema.__name__}"
        if bases:
            heading += " extends " + ", ".join(map(self.reference, bases))
        lines = []
        if schema.__doc__ and not schema.__doc__.startswith(f"{schema.__name__}("):
            lines.append(f"/** {' '.join(schema.__doc__.split())} */")
        lines.append(heading + " {")
        for key, hint in hints.items():
            if key in inherited:
                continue
            optional = typing.get_origin(hint) is typing.NotRequired
            if optional:
                hint = typing.get_args(hint)[0]
            mark = "?" if optional else ""
            lines.append(f"  readonly {key}{mark}: {self.reference(hint)};")
        return "\n".join([*lines, "}"])


def _literals(values: typing.Iterable[object]) -> str:
    return " | ".join(
        f'"{value}"' if isinstance(value, str) else str(value) for value in values
    )


def generate() -> str:
    """Return the TypeScript the schema modules describe."""
    sys.path.insert(0, str(ROOT))
    emitter = Emitter()
    for name in SCHEMAS:
        module = __import__(name, fromlist=["_"])
        for value in vars(module).values():
            if typing.is_typeddict(value) and value.__module__ == name:
                emitter.reference(value)
    return HEADER + "".join(
        f"\n{declaration}\n" for declaration in emitter.declarations.values()
    )


def main(arguments: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="fail if the file is out of date"
    )
    options = parser.parse_args(arguments)
    expected = generate()
    target = ROOT / OUTPUT
    if not options.check:
        target.write_text(expected)
        return 0
    if target.exists() and target.read_text() == expected:
        return 0
    print(f"{OUTPUT} is out of date; run `python scripts/contract_types.py`.")
    return 1


if __name__ == "__main__":
    sys.exit(main())
